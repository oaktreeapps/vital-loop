import 'package:flutter/material.dart';

/// A centered spinner with a short text, shown until the first surface
/// arrives.
class FlowLoadingView extends StatelessWidget {
  /// Creates the loading view with [label].
  const FlowLoadingView({super.key, required this.label});

  /// The text under the spinner, e.g. the flow's `TrackingFlow.loadingLabel`.
  final String label;

  /// Builds the spinner and the text.
  @override
  Widget build(BuildContext context) {
    return Center(
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          const CircularProgressIndicator(),
          const SizedBox(height: 16),
          Text(label),
        ],
      ),
    );
  }
}
